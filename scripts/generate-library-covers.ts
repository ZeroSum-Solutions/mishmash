// ---------------------------------------------------------------------------
// Contact-sheet detection & tile extraction
//
// Some Figma-only kits (e.g. "62 screens", "Ai personal health") have no
// bundled preview image of their own — the only thing available is the
// .fig file's embedded `thumbnail.png`, which for a many-frame canvas is
// Figma's render of the WHOLE canvas: a grid of dozens of small tiles. Using
// that directly as a hero is exactly the "tiny blurry contact sheet" the PRD
// forbids. The same shape can occur from a single bundled raster preview
// too. Detect the grid and slice it into individual tiles so the composed
// cover shows a handful of screens at legible size instead.
// ---------------------------------------------------------------------------

type SheetTileRaw = { x: number; y: number; w: number; h: number; dataUri: string; byteLen: number };
type SheetAnalysisRaw = { cols: number; rows: number; tiles: SheetTileRaw[] } | null;

// Runs inside the Playwright page (browser context), not Node — see the
// ambient DOM declarations above. Pragmatic heuristic, not real computer
// vision: sample columns/rows for the fraction of pixels matching the
// dominant background color, treat long near-100%-background runs as
// gutters, and require the resulting tile grid to be at least 2x3 and
// reasonably uniform in size before calling it a sheet. A genuine
// single-screen preview (the common case) fails one of those checks and
// returns null, leaving the original image untouched.
async function sheetAnalysisBrowserFn(srcDataUri: string): Promise<SheetAnalysisRaw> {
  const img = new Image();
  const loaded = new Promise<void>((resolve, reject) => {
    img.onload = () => resolve();
    img.onerror = () => reject(new Error('image failed to load'));
  });
  img.src = srcDataUri;
  await loaded;
  const w = img.naturalWidth;
  const h = img.naturalHeight;
  if (!w || !h) return null;
  if (w * h > 20_000_000) return null; // guard against runaway analysis on huge sources

  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const ctx = canvas.getContext('2d');
  if (!ctx) return null;
  ctx.drawImage(img, 0, 0);
  const { data } = ctx.getImageData(0, 0, w, h);

  const pixelAt = (x: number, y: number): [number, number, number] => {
    const i = (y * w + x) * 4;
    return [data[i] ?? 0, data[i + 1] ?? 0, data[i + 2] ?? 0];
  };

  // Dominant background color from a coarse sample grid (more robust than
  // trusting a single corner, which can itself sit on a tile).
  const votes = new Map<string, number>();
  const grid = 24;
  for (let gy = 0; gy < grid; gy++) {
    for (let gx = 0; gx < grid; gx++) {
      const x = Math.min(w - 1, Math.floor((gx / grid) * w));
      const y = Math.min(h - 1, Math.floor((gy / grid) * h));
      const [r, g, b] = pixelAt(x, y);
      const key = `${Math.round(r / 8) * 8},${Math.round(g / 8) * 8},${Math.round(b / 8) * 8}`;
      votes.set(key, (votes.get(key) ?? 0) + 1);
    }
  }
  let bg: [number, number, number] = [0, 0, 0];
  let bestVotes = -1;
  for (const [key, count] of votes) {
    if (count > bestVotes) {
      bestVotes = count;
      const parts = key.split(',').map(Number);
      bg = [parts[0] ?? 0, parts[1] ?? 0, parts[2] ?? 0];
    }
  }
  const closeToBg = (p: [number, number, number], tol = 16): boolean =>
    Math.abs(p[0] - bg[0]) <= tol && Math.abs(p[1] - bg[1]) <= tol && Math.abs(p[2] - bg[2]) <= tol;

  const colStepY = Math.max(1, Math.floor(h / 260));
  const colBgFrac: number[] = new Array(w).fill(0);
  let sampledRows = 0;
  for (let y = 0; y < h; y += colStepY) {
    sampledRows++;
    for (let x = 0; x < w; x++) {
      if (closeToBg(pixelAt(x, y))) colBgFrac[x] = (colBgFrac[x] ?? 0) + 1;
    }
  }
  for (let x = 0; x < w; x++) colBgFrac[x] = (colBgFrac[x] ?? 0) / Math.max(1, sampledRows);

  const rowStepX = Math.max(1, Math.floor(w / 260));
  const rowBgFrac: number[] = new Array(h).fill(0);
  let sampledCols = 0;
  for (let x = 0; x < w; x += rowStepX) {
    sampledCols++;
    for (let y = 0; y < h; y++) {
      if (closeToBg(pixelAt(x, y))) rowBgFrac[y] = (rowBgFrac[y] ?? 0) + 1;
    }
  }
  for (let y = 0; y < h; y++) rowBgFrac[y] = (rowBgFrac[y] ?? 0) / Math.max(1, sampledCols);

  const findRuns = (frac: number[], threshold: number, minRun: number): [number, number][] => {
    const runs: [number, number][] = [];
    let start: number | null = null;
    for (let i = 0; i < frac.length; i++) {
      const isGutter = (frac[i] ?? 0) >= threshold;
      if (!isGutter) {
        if (start === null) start = i;
      } else if (start !== null) {
        if (i - start >= minRun) runs.push([start, i]);
        start = null;
      }
    }
    if (start !== null && frac.length - start >= minRun) runs.push([start, frac.length]);
    return runs;
  };

  const colRuns = findRuns(colBgFrac, 0.88, Math.max(12, Math.floor(w * 0.015)));
  const rowRuns = findRuns(rowBgFrac, 0.88, Math.max(12, Math.floor(h * 0.015)));
  const cols = colRuns.length;
  const rows = rowRuns.length;
  if (cols < 2 || rows < 2 || cols * rows < 6 || cols * rows > 200) return null;

  // Regularity: a real screen grid has near-uniform tile sizes. A row of
  // unrelated content blobs (not a grid) will not.
  const widths = colRuns.map(([a, b]) => b - a);
  const heights = rowRuns.map(([a, b]) => b - a);
  const mean = (arr: number[]): number => arr.reduce((s, v) => s + v, 0) / arr.length;
  const stdev = (arr: number[], m: number): number => Math.sqrt(mean(arr.map((v) => (v - m) ** 2)));
  const wMean = mean(widths);
  const hMean = mean(heights);
  if (wMean <= 0 || hMean <= 0) return null;
  if (stdev(widths, wMean) / wMean > 0.35 || stdev(heights, hMean) / hMean > 0.35) return null;

  const tiles: SheetTileRaw[] = [];
  for (const rowRun of rowRuns) {
    const [ry0, ry1] = rowRun;
    for (const colRun of colRuns) {
      const [cx0, cx1] = colRun;
      const tw = cx1 - cx0;
      const th = ry1 - ry0;
      if (tw < 20 || th < 20) continue;
      const tileCanvas = document.createElement('canvas');
      tileCanvas.width = tw;
      tileCanvas.height = th;
      const tileCtx = tileCanvas.getContext('2d');
      if (!tileCtx) continue;
      tileCtx.drawImage(canvas, cx0, ry0, tw, th, 0, 0, tw, th);
      const dataUri = tileCanvas.toDataURL('image/jpeg', 0.85);
      tiles.push({ x: cx0, y: ry0, w: tw, h: th, dataUri, byteLen: dataUri.length });
    }
  }
  if (tiles.length < 3) return null;
  return { cols, rows, tiles };
}

function readRawDataUri(imgPath: string): string | null {
  try {
    const ext = path.extname(imgPath).toLowerCase();
    const mime = ext === '.png' ? 'image/png' : ext === '.webp' ? 'image/webp' : 'image/jpeg';
    const buf = fs.readFileSync(imgPath);
    if (buf.length > 15 * 1024 * 1024) return null; // guard against pathological sources
    return `data:${mime};base64,${buf.toString('base64')}`;
  } catch {
    return null;
  }
}

function writeDataUriToFile(dataUri: string, outPath: string): boolean {
  const match = /^data:[^;]+;base64,(.+)$/s.exec(dataUri);
  const base64 = match?.[1];
  if (!base64) return false;
  try {
    fs.writeFileSync(outPath, Buffer.from(base64, 'base64'));
    return true;
  } catch {
    return false;
  }
}

// A many-frame .fig's embedded thumbnail.png is Figma-generated and capped
// at roughly 400px on its long edge regardless of the source file — this is
// a platform limit, not something this script controls. Sliced into even a
// modest grid, individual tiles land well under 100px on a side: no amount
// of grid-detection accuracy fixes that, so a detected tile smaller than
// this floor is refused rather than blown up into a blurry hero/thumbnail.
const MIN_TILE_DIM = 140;

// Empirically (live-app review, 2026-08-10), pure pixel gutter-detection is
// unreliable on this dataset: it missed both known contact sheets ("62
// screens", "Ai personal health" — their grids are irregular/over-fragmented
// at 400px) and produced false positives on genuinely single-hero
// promotional images ("Aura finance widgets", "Ventr") whose incidental
// dark-background composition coincidentally resembled a regular grid,
// yielding badly upscaled blurry crops — a worse defect than the one being
// fixed. The catalog's human-curated `description` field was written by
// directly reading each kit's actual thumbnail, so explicit density
// language ("dense tile of ... screens", "62 tiled ... screens", "40+
// screens", "dozens of ... screens") is a precise, zero-guesswork signal
// that pixel analysis could not reliably reconstruct. Pixel slicing is kept
// as a secondary confirmation step (gated by this text signal, and by
// MIN_TILE_DIM below) rather than the primary detector.
const DENSE_SHEET_RE =
  /\b\d+\+?\s+(tiled\s+)?screens?\b|\btiled\b[^.]{0,40}\bscreens?\b|\bdense\s+(tile|grid)\s+of\b[^.]{0,60}\bscreens?\b|\bdozens\s+of\b[^.]{0,30}\bscreens?\b/i;
const SHEET_NEGATION_RE = /\bnot\b[^.]{0,25}\bscreens?\b|\bscreens?\b[^.]{0,10}\bnot\b/i;

// "Ai personal health" was confirmed by direct visual inspection (Read on
// the current .jpg during the C5 follow-up) to be a dense multi-screen
// contact sheet, even though its curated description doesn't use
// "dense/tiled/dozens" language the automatic text gate matches on.
const KNOWN_CONTACT_SHEET_IDS = new Set<string>(['01-ui8-kits-ai-personal-health']);

function looksLikeDenseSheet(item: CatalogItem): boolean {
  if (KNOWN_CONTACT_SHEET_IDS.has(item.id)) return true;
  const text = `${item.label} ${item.description ?? ''}`;
  return DENSE_SHEET_RE.test(text) && !SHEET_NEGATION_RE.test(text);
}

type SheetRemediation = {
  screens: string[];
  captionNote: string;
  galleryTiles: string[]; // data URIs, up to 4, for the daemon gallery strip
  grid: { cols: number; rows: number; totalTiles: number };
};

// Attempts to detect+slice a contact sheet at `imgPath`, ONLY for images the
// caller has already confirmed are dense sheets via `looksLikeDenseSheet`.
// Returns null when no clean-enough grid is found, or when the detected
// tiles fall under MIN_TILE_DIM — in both cases the caller must not use the
// source image at all (see the fig-thumbnail call site: it downgrades to
// the typographic fallback rather than risk a tiny/blurry cover).
async function tryRemediateContactSheet(pageObj: PlaywrightPage, imgPath: string): Promise<SheetRemediation | null> {
  const rawDataUri = readRawDataUri(imgPath);
  if (!rawDataUri) return null;
  let analysis: SheetAnalysisRaw;
  try {
    analysis = await pageObj.evaluate<SheetAnalysisRaw, string>(sheetAnalysisBrowserFn, rawDataUri);
  } catch {
    return null;
  }
  if (!analysis) return null;
  const ranked = [...analysis.tiles].sort((a, b) => b.byteLen - a.byteLen);
  const top = ranked.slice(0, 5);
  if (top.length < 3) return null;
  const avgW = top.reduce((sum, t) => sum + t.w, 0) / top.length;
  const avgH = top.reduce((sum, t) => sum + t.h, 0) / top.length;
  if (avgW < MIN_TILE_DIM || avgH < MIN_TILE_DIM) return null;
  return {
    screens: top.map((t) => t.dataUri),
    captionNote: `${analysis.cols}×${analysis.rows} screens (sliced)`,
    galleryTiles: top.slice(1, 5).map((t) => t.dataUri),
    grid: { cols: analysis.cols, rows: analysis.rows, totalTiles: analysis.tiles.length },
  };
}

async function screenshotHtmlFile(
  page_: PlaywrightPage,
  htmlPath: string,
  outPngPath: string,
  { width = 1280, height = 800 } = {},
): Promise<void> {
  await page_.setViewportSize({ width, height });
  await page_.goto(pathToFileURL(htmlPath).href, { waitUntil: 'networkidle', timeout: 15000 }).catch(() => {});
  // Many templates lazy-load hero imagery via IntersectionObserver, which
  // never fires unless the page has actually scrolled. Nudge it, then settle
  // a few pixels below true top (not exactly 0) — some templates gate their
  // hero reveal on having scrolled at all, and a few px is enough to cross
  // that threshold without leaving the frame visibly scrolled.
  await page_
    .evaluate(async () => {
      const step = Math.max(window.innerHeight, 400);
      const max = Math.min(document.body.scrollHeight, step * 6);
      for (let y = 0; y <= max; y += step) {
        window.scrollTo(0, y);
        await new Promise((r) => setTimeout(r, 120));
      }
      window.scrollTo(0, 24);
      await new Promise((r) => setTimeout(r, 150));
    })
    .catch(() => {});
  await page_.waitForTimeout(300);
  await page_.screenshot({ path: outPngPath, type: 'png' });
}

async function renderComposedPage(
  page_: PlaywrightPage,
  htmlContent: string,
  outJpgPath: string,
  { width = 1600, height = 1000 } = {},
): Promise<void> {
  const tmpHtml = path.join(TMP_DIR, `compose-${crypto.randomUUID()}.html`);
  fs.writeFileSync(tmpHtml, htmlContent, 'utf8');
  await page_.setViewportSize({ width, height });
  await page_.goto(pathToFileURL(tmpHtml).href, { waitUntil: 'load', timeout: 15000 });
  await page_.waitForTimeout(120);
  await page_.screenshot({ path: outJpgPath, type: 'jpeg', quality: 90 });
}

