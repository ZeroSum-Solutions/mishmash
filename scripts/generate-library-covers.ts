type ProcessResult = {
  outcome: 'processed' | 'fallback';
  html: string;
  galleryTiles?: string[];
  sheetGrid?: { cols: number; rows: number; totalTiles: number };
};

async function processKitSheet(pageObj: PlaywrightPage, item: CatalogItem, dir: string): Promise<ProcessResult> {
  let screens: string[] = [];
  let captionNote: string | null = null;

  const htmls = findHtmlCandidates(dir).slice(0, 7);
  if (htmls.length) {
    const rendered: { tmpPng: string; size: number }[] = [];
    for (const h of htmls) {
      const tmpPng = path.join(TMP_DIR, `html-${crypto.randomUUID()}.png`);
      try {
        await screenshotHtmlFile(pageObj, h, tmpPng);
        const size = fs.statSync(tmpPng).size;
        rendered.push({ tmpPng, size });
      } catch {
        // skip this page, try the next candidate
      }
    }
    // A near-empty/pre-animation capture compresses to a much smaller PNG
    // than a busy real page, so ranking by rendered file size is a cheap,
    // reliable proxy for "this frame actually shows content" — use it to
    // pick the hero rather than trusting filename order alone.
    rendered.sort((a, b) => b.size - a.size);
    for (const r of rendered.slice(0, 5)) {
      const uri = toDataUri(r.tmpPng);
      if (uri) screens.push(uri);
    }
  }

  // A bundled raster living next to the asset (Preview/cover.png and
  // similar) is a real export of the kit's own screens, sized for exactly
  // this purpose. A .fig's embedded thumbnail.png is Figma's incidental
  // canvas-navigator render, capped around 400px on its long edge regardless
  // of source size (see MIN_TILE_DIM below) — worse by construction whenever
  // a bundled raster exists. Try the bundled raster tier first so it outranks
  // the fig thumbnail rather than only being reached when the fig extraction
  // fails outright.
  if (screens.length === 0) {
    const rasters = findRasterCandidates(dir).slice(0, 5);
    for (const r of rasters) {
      const uri = toDataUri(r.path);
      if (uri) screens.push(uri);
      if (screens.length >= 5) break;
    }
  }

  if (screens.length === 0) {
    const figs = findFigFiles(dir);
    if (figs.length) {
      const firstFig = figs[0];
      const thumb = firstFig ? extractFigThumbnail(firstFig.path) : null;
      if (thumb) {
        // A many-frame .fig's embedded thumbnail.png is Figma's render of
        // the WHOLE canvas — for a kit with dozens of screens that IS a
        // contact sheet. Only check kits the curated description (or a
        // manually-verified id) already confirms are dense: see
        // looksLikeDenseSheet's comment for why pixel analysis alone is not
        // trusted as the primary signal here.
        if (looksLikeDenseSheet(item)) {
          const remediation = await tryRemediateContactSheet(pageObj, thumb);
          if (remediation) {
            return {
              outcome: 'processed',
              html: composeKitSheetHtml({
                label: item.label,
                categoryLabel: categoryLabelFor(item.category),
                screens: remediation.screens,
                captionNote: remediation.captionNote,
              }),
              galleryTiles: remediation.galleryTiles,
              sheetGrid: remediation.grid,
            };
          }
          // Confirmed dense sheet, but the embedded thumbnail has no tile
          // resolution worth slicing (MIN_TILE_DIM) or no clean grid was
          // found. Using the whole tiny grid as a single hero is exactly
          // the "tiny blurry contact sheet" this exists to avoid — a clean
          // typographic cover beats a bad image.
          return { outcome: 'fallback', html: composeFallbackFor(item, dir) };
        }
        // Single-thumbnail hero path: apply the same MIN_TILE_DIM floor the
        // sliced-tile path already enforces. A sub-floor thumbnail blown up
        // to fill the hero frame is exactly the "blurry cover" this script
        // exists to avoid — a clean typographic fallback beats it.
        const dims = getImagePixelDimensions(thumb);
        const meetsFloor = dims !== null && dims.width >= MIN_TILE_DIM && dims.height >= MIN_TILE_DIM;
        if (meetsFloor) {
          const uri = toDataUri(thumb);
          if (uri) {
            screens = [uri];
            captionNote = 'Figma design file';
          }
        }
      }
    }
  }

  if (screens.length === 0) {
    return { outcome: 'fallback', html: composeFallbackFor(item, dir) };
  }

  const html = composeKitSheetHtml({
    label: item.label,
    categoryLabel: categoryLabelFor(item.category),
    screens,
    captionNote,
  });
  return { outcome: 'processed', html };
}

async function processIconGrid(item: CatalogItem, dir: string): Promise<ProcessResult> {
  const allSvg = walkFiles(dir, { maxFiles: 8000 })
    .filter((f) => f.toLowerCase().endsWith('.svg'))
    .filter((f) => !/preview|iconjar|editables[_-]?figma[_-]?sketch/i.test(f));
  const allPng = walkFiles(dir, { maxFiles: 8000 })
    .filter((f) => f.toLowerCase().endsWith('.png'))
    .filter((f) => !/preview/i.test(f));
  const pool = allSvg.length ? allSvg : allPng;
  if (!pool.length) return { outcome: 'fallback', html: composeFallbackFor(item, dir) };

  const byDir = new Map<string, string[]>();
  for (const f of pool) {
    const d = path.dirname(f);
    const arr = byDir.get(d);
    if (arr) {
      arr.push(f);
    } else {
      byDir.set(d, [f]);
    }
  }
  const dirs = [...byDir.keys()];

  const total = pool.length;
  let target = total;
  let cols = Math.min(5, total);
  let rows = Math.ceil(total / cols);
  if (total >= 32) {
    target = 32;
    cols = 8;
    rows = 4;
  } else if (total >= 24) {
    target = 24;
    cols = 6;
    rows = 4;
  } else if (total >= 15) {
    target = 15;
    cols = 5;
    rows = 3;
  }

  const picked: string[] = [];
  while (picked.length < target) {
    let progressed = false;
    for (const d of dirs) {
      const arr = byDir.get(d);
      if (arr && arr.length) {
        const next = arr.shift();
        if (next !== undefined) {
          picked.push(next);
          progressed = true;
        }
      }
      if (picked.length >= target) break;
    }
    if (!progressed) break;
  }

  const icons: IconCell[] = [];
  for (const f of picked) {
    if (f.toLowerCase().endsWith('.svg')) {
      const svg = readSvgInline(f);
      if (svg) icons.push({ svg });
    } else {
      const uri = toDataUri(f, { maxDim: 200 });
      if (uri) icons.push({ dataUri: uri });
    }
  }
  if (!icons.length) return { outcome: 'fallback', html: composeFallbackFor(item, dir) };

  const html = composeIconGridHtml({
    label: item.label,
    categoryLabel: categoryLabelFor(item.category),
    icons,
    cols,
    rows,
  });
  return { outcome: 'processed', html };
}

async function processMissingOther(pageObj: PlaywrightPage, item: CatalogItem, dir: string): Promise<ProcessResult> {
  const htmls = findHtmlCandidates(dir);
  if (htmls.length) {
    const firstHtml = htmls[0];
    const tmpPng = path.join(TMP_DIR, `html-${crypto.randomUUID()}.png`);
    try {
      if (firstHtml) {
        await screenshotHtmlFile(pageObj, firstHtml, tmpPng, { width: 1600, height: 1000 });
        const uri = toDataUri(tmpPng, { maxDim: 1400 });
        if (uri) {
          return {
            outcome: 'processed',
            html: composeHeroCoverHtml({ label: item.label, categoryLabel: categoryLabelFor(item.category), dataUri: uri }),
          };
        }
      }
    } catch {
      // fall through to other strategies
    }
  }

  const rasters = findRasterCandidates(dir);
  const firstRaster = rasters[0];
  if (firstRaster) {
    const uri = toDataUri(firstRaster.path, { maxDim: 1400 });
    if (uri) {
      return {
        outcome: 'processed',
        html: composeHeroCoverHtml({ label: item.label, categoryLabel: categoryLabelFor(item.category), dataUri: uri }),
      };
    }
  }

  const zips = findZipFiles(dir);
  const firstZip = zips[0];
  if (firstZip) {
    const img = extractBestImageFromZip(firstZip.path);
    if (img) {
      const uri = toDataUri(img, { maxDim: 1400 });
      if (uri) {
        return {
          outcome: 'processed',
          html: composeHeroCoverHtml({ label: item.label, categoryLabel: categoryLabelFor(item.category), dataUri: uri }),
        };
      }
    }
  }

  return { outcome: 'fallback', html: composeFallbackFor(item, dir) };
}

