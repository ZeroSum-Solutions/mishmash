function isMissing(item: CatalogItem): boolean {
  if (item.cover_policy) return false;
  if (!item.thumb) return true;
  return !fs.existsSync(path.join(ASSETS_ROOT, item.thumb));
}

type CategoryCounts = { processed: number; fallback: number; skipped: number; error: number };

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  let onlyFilter: string | null = null;
  const onlyIdx = args.indexOf('--only');
  if (onlyIdx !== -1) onlyFilter = args[onlyIdx + 1] ?? null;

  fs.mkdirSync(THUMBS_DIR, { recursive: true });
  fs.mkdirSync(META_DIR, { recursive: true });
  fs.mkdirSync(BACKUP_DIR, { recursive: true });

  const raw = fs.readFileSync(CATALOG_PATH, 'utf8');
  const data = JSON.parse(raw) as CatalogData;

  if (!fs.existsSync(BACKUP_PATH)) {
    fs.writeFileSync(BACKUP_PATH, raw);
    console.log(`Backed up catalog.json -> ${BACKUP_PATH}`);
  } else {
    console.log(`Backup already exists at ${BACKUP_PATH} (not overwritten)`);
  }

  const allItems: CatalogItem[] = [];
  for (const group of data.groups ?? []) {
    for (const item of group.items ?? []) allItems.push(item);
  }

  // cover_policy items are exempt from this generator entirely — the kit/icon
  // category sweep must not overwrite a policy-protected cover.
  let scope = allItems.filter(
    (it) => !it.cover_policy && (KIT_CATEGORIES.has(it.category) || it.category === 'icons' || isMissing(it)),
  );
  if (onlyFilter) {
    scope = scope.filter((it) => it.category === onlyFilter || it.id === onlyFilter);
  }
  console.log(`Scope: ${scope.length} item(s)`);

  const browser = await chromium.launch();
  const pageObj = await browser.newPage();

  const counts: Record<string, CategoryCounts> = {};
  let changed = false;
  const remediatedSheets: { id: string; cols: number; rows: number; totalTiles: number; galleryCount: number }[] = [];

  for (const item of scope) {
    const cat = item.category || '(none)';
    counts[cat] ??= { processed: 0, fallback: 0, skipped: 0, error: 0 };
    const catCounts = counts[cat];

    const metaPath = path.join(META_DIR, `${item.id}.json`);
    const outJpg = path.join(THUMBS_DIR, `${item.id}.jpg`);
    if (fs.existsSync(metaPath) && fs.existsSync(outJpg)) {
      // Render is already done, but catalog.json's thumb field may not point
      // at it — e.g. a crash between writing the jpg and patching the
      // catalog, or a future catalog regen that dropped the field. Relink
      // rather than silently leaving a stale/null thumb.
      const relThumb = path.relative(ASSETS_ROOT, outJpg);
      if (item.thumb !== relThumb) {
        item.thumb = relThumb;
        changed = true;
      }
      catCounts.skipped += 1;
      continue;
    }

    const dir = path.join(ASSETS_ROOT, item.rel);
    if (!fs.existsSync(dir) || !fs.statSync(dir).isDirectory()) {
      catCounts.error += 1;
      console.warn(`  ! missing item directory for ${item.id}: ${item.rel}`);
      continue;
    }

    try {
      let result: ProcessResult;
      if (item.category === 'icons') {
        result = await processIconGrid(item, dir);
      } else if (KIT_CATEGORIES.has(item.category)) {
        result = await processKitSheet(pageObj, item, dir);
      } else {
        result = await processMissingOther(pageObj, item, dir);
      }

      await renderComposedPage(pageObj, result.html, outJpg);

      let galleryCount = 0;
      if (result.galleryTiles?.length) {
        for (let i = 0; i < result.galleryTiles.length && i < 4; i++) {
          const tileUri = result.galleryTiles[i];
          if (!tileUri) continue;
          const tilePath = path.join(THUMBS_DIR, `${item.id}-tile-${i + 1}.jpg`);
          if (writeDataUriToFile(tileUri, tilePath)) galleryCount++;
        }
      }
      if (result.sheetGrid) {
        remediatedSheets.push({ id: item.id, ...result.sheetGrid, galleryCount });
      }

      fs.writeFileSync(
        metaPath,
        JSON.stringify(
          {
            category: item.category,
            outcome: result.outcome,
            generatedAt: new Date().toISOString(),
            ...(result.sheetGrid ? { sheetGrid: result.sheetGrid, galleryTiles: galleryCount } : {}),
          },
          null,
          2,
        ),
      );

      const relThumb = path.relative(ASSETS_ROOT, outJpg);
      if (item.thumb !== relThumb) {
        item.thumb = relThumb;
        changed = true;
      }
      catCounts[result.outcome === 'fallback' ? 'fallback' : 'processed'] += 1;
      const sheetNote = result.sheetGrid ? ` (sliced ${result.sheetGrid.cols}x${result.sheetGrid.rows} sheet, ${galleryCount} gallery tiles)` : '';
      console.log(`  ${result.outcome === 'fallback' ? '[fallback] ' : '[ok]       '}${item.id}${sheetNote}`);
    } catch (err) {
      catCounts.error += 1;
      console.warn(`  ! error on ${item.id}: ${errorMessage(err)}`);
    }
  }

  await browser.close();
  fs.rmSync(TMP_DIR, { recursive: true, force: true });

  if (changed) {
    fs.writeFileSync(CATALOG_PATH, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
    console.log('catalog.json updated (thumb fields only).');
  } else {
    console.log('catalog.json unchanged (nothing new to write).');
  }

  console.log('\nSummary:');
  console.log(
    'category'.padEnd(16),
    'processed'.padEnd(10),
    'fallback-typographic'.padEnd(22),
    'skipped-ok'.padEnd(12),
    'error',
  );
  const totals: CategoryCounts = { processed: 0, fallback: 0, skipped: 0, error: 0 };
  for (const [catName, c] of Object.entries(counts)) {
    console.log(catName.padEnd(16), String(c.processed).padEnd(10), String(c.fallback).padEnd(22), String(c.skipped).padEnd(12), String(c.error));
    totals.processed += c.processed;
    totals.fallback += c.fallback;
    totals.skipped += c.skipped;
    totals.error += c.error;
  }
  console.log(
    'TOTAL'.padEnd(16),
    String(totals.processed).padEnd(10),
    String(totals.fallback).padEnd(22),
    String(totals.skipped).padEnd(12),
    String(totals.error),
  );

  if (remediatedSheets.length) {
    console.log('\nContact-sheet remediation:');
    for (const s of remediatedSheets) {
      console.log(`  ${s.id}: ${s.cols}x${s.rows} grid (${s.totalTiles} tiles detected) -> ${s.galleryCount} gallery tiles`);
    }
  }
}

main().catch((err: unknown) => {
  console.error(err);
  process.exitCode = 1;
});
