// Purposeful cover generator for the mishmash-assets design library (PRD C5).
//
// Every catalog item should get a cover that accurately shows what it
// contains, instead of a random bundled image or a tiny contact sheet:
//   - ui-kit / design-system items -> a kit reconstruction sheet: 1-5 of the
//     kit's own strongest screens (rendered live when the kit ships static
//     HTML, else its own bundled preview imagery, else the Figma-embedded
//     thumbnail), composed on a quiet dark studio surface.
//   - icons items -> an even grid of the set's own individual icon files.
//   - any item with no usable content at all falls back to a typographic
//     cover: name + category + file-type chips, never blank.
//
// catalog.json's `category`/`description` fields were hand-classified in an
// earlier task (see scripts/design-taxonomy.ts). build_catalog.py in
// mishmash-assets/.catalog REGENERATES those fields from folder names on
// every run, so this script never invokes it — it writes thumbs on disk and
// patches only the `thumb` field of processed catalog.json items directly.
//
// Usage:
//   node scripts/generate-library-covers.ts [--only <category|id>]
//
// The mishmash-assets checkout defaults to the maintainer's path; set
// OD_MISHMASH_ASSETS_DIR to point at a checkout under a different home.

