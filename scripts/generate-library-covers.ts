function walkFiles(dir: string, { maxFiles = 6000, maxDepth = 10 } = {}): string[] {
  const out: string[] = [];
  function visit(d: string, depth: number): void {
    if (depth > maxDepth || out.length >= maxFiles) return;
    let entries: fs.Dirent[];
    try {
      entries = fs.readdirSync(d, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      if (out.length >= maxFiles) return;
      if (e.name.startsWith('.')) continue;
      if (e.isDirectory()) {
        if (SKIP_DIRS.has(e.name)) continue;
        visit(path.join(d, e.name), depth + 1);
      } else if (e.isFile()) {
        out.push(path.join(d, e.name));
      }
    }
  }
  visit(dir, 0);
  return out;
}

type RasterCandidate = { path: string; size: number; name: string };

function findRasterCandidates(dir: string): RasterCandidate[] {
  const files = walkFiles(dir);
  const rasters: RasterCandidate[] = [];
  for (const f of files) {
    const ext = path.extname(f).toLowerCase();
    if (!RASTER_EXT.has(ext)) continue;
    let size: number;
    try {
      size = fs.statSync(f).size;
    } catch {
      continue;
    }
    if (size < 20 * 1024) continue; // skip spacer/icon-sized files
    rasters.push({ path: f, size, name: path.basename(f) });
  }
  rasters.sort((a, b) => {
    const aPref = PREF_RE.test(a.name) && !NEG_RE.test(a.name) ? 1 : 0;
    const bPref = PREF_RE.test(b.name) && !NEG_RE.test(b.name) ? 1 : 0;
    if (aPref !== bPref) return bPref - aPref;
    const aNeg = NEG_RE.test(a.name) ? 1 : 0;
    const bNeg = NEG_RE.test(b.name) ? 1 : 0;
    if (aNeg !== bNeg) return aNeg - bNeg;
    return b.size - a.size;
  });
  return rasters;
}

type SizedFile = { path: string; size: number };

function findFigFiles(dir: string): SizedFile[] {
  return walkFiles(dir)
    .filter((f) => f.toLowerCase().endsWith('.fig'))
    .map((f) => ({ path: f, size: fs.statSync(f).size }))
    .sort((a, b) => b.size - a.size);
}

function extractFigThumbnail(figPath: string): string | null {
  try {
    const listing = execFileSync('unzip', ['-l', figPath], { encoding: 'utf8', maxBuffer: 20 * 1024 * 1024 });
    const line = listing.split('\n').find((l) => /thumbnail\.png$/i.test(l.trim()));
    if (!line) return null;
    const entry = line.trim().split(/\s+/).slice(3).join(' ');
    const buf = execFileSync('unzip', ['-p', figPath, entry], { maxBuffer: 50 * 1024 * 1024 });
    const tmp = path.join(TMP_DIR, `fig-thumb-${crypto.randomUUID()}.png`);
    fs.writeFileSync(tmp, buf);
    return tmp;
  } catch {
    return null;
  }
}

function findHtmlCandidates(dir: string): string[] {
  const files = walkFiles(dir).filter((f) => f.toLowerCase().endsWith('.html'));
  const filtered = files.filter((f) => {
    const base = path.basename(f).toLowerCase();
    if (base === '404.html' || base === 'sitemap.html') return false;
    if (f.toLowerCase().includes(`${path.sep}documentation${path.sep}`)) return false;
    return true;
  });
  const score = (f: string): number => {
    const base = path.basename(f).toLowerCase();
    // Named demo variants (index-creative-agency.html) are real pages; a bare
    // index.html is often just a template picker/hub for multi-demo kits, so
    // it ranks below named variants but above unrelated interior pages.
    if (/^(index|home|landing|main)-.+\.html$/.test(base)) return 2;
    if (base === 'index.html' || base === 'home.html' || base === 'landing.html' || base === 'main.html') return 1;
    return 0;
  };
  filtered.sort((a, b) => score(b) - score(a));
  return filtered;
}

function findZipFiles(dir: string): SizedFile[] {
  return walkFiles(dir)
    .filter((f) => f.toLowerCase().endsWith('.zip'))
    .map((f) => ({ path: f, size: fs.statSync(f).size }))
    .sort((a, b) => b.size - a.size);
}

function extractBestImageFromZip(zipPath: string): string | null {
  try {
    const listing = execFileSync('unzip', ['-l', zipPath], { encoding: 'utf8', maxBuffer: 20 * 1024 * 1024 });
    const candidates: { entry: string; size: number }[] = [];
    for (const line of listing.split('\n')) {
      const m = line.trim().match(/^(\d+)\s+\S+\s+\S+\s+(.+)$/);
      if (!m) continue;
      const size = parseInt(m[1] ?? '0', 10);
      const entry = m[2] ?? '';
      if (!/\.(png|jpe?g|webp)$/i.test(entry)) continue;
      if (size < 20 * 1024) continue;
      candidates.push({ entry, size });
    }
    candidates.sort((a, b) => {
      const aPref = PREF_RE.test(a.entry) && !NEG_RE.test(a.entry) ? 1 : 0;
      const bPref = PREF_RE.test(b.entry) && !NEG_RE.test(b.entry) ? 1 : 0;
      if (aPref !== bPref) return bPref - aPref;
      return b.size - a.size;
    });
    const best = candidates[0];
    if (!best) return null;
    const buf = execFileSync('unzip', ['-p', zipPath, best.entry], { maxBuffer: 50 * 1024 * 1024 });
    const ext = path.extname(best.entry) || '.png';
    const tmp = path.join(TMP_DIR, `zip-img-${crypto.randomUUID()}${ext}`);
    fs.writeFileSync(tmp, buf);
    return tmp;
  } catch {
    return null;
  }
}

// `sips` (already used for resizing above) also reports pixel dimensions
// without decoding the file in-process — used to floor-check a would-be hero
// image before committing to it, the same way MIN_TILE_DIM floors sliced
// contact-sheet tiles.
function getImagePixelDimensions(imgPath: string): { width: number; height: number } | null {
  try {
    const out = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', imgPath], { encoding: 'utf8' });
    const width = Number(/pixelWidth:\s*(\d+)/.exec(out)?.[1]);
    const height = Number(/pixelHeight:\s*(\d+)/.exec(out)?.[1]);
    if (!Number.isFinite(width) || !Number.isFinite(height) || width <= 0 || height <= 0) return null;
    return { width, height };
  } catch {
    return null;
  }
}

function extensionHistogram(dir: string): [string, number][] {
  const counts = new Map<string, number>();
  for (const f of walkFiles(dir, { maxFiles: 3000 })) {
    const ext = path.extname(f).toLowerCase() || '(no ext)';
    counts.set(ext, (counts.get(ext) || 0) + 1);
  }
  return [...counts.entries()].sort((a, b) => b[1] - a[1]);
}

function toDataUri(imgPath: string, { maxDim = 900 } = {}): string | null {
  const ext = path.extname(imgPath).toLowerCase();
  let srcPath = imgPath;
  let mime = ext === '.png' ? 'image/png' : ext === '.webp' ? 'image/webp' : 'image/jpeg';
  try {
    const size = fs.statSync(imgPath).size;
    if (size > 300 * 1024) {
      const tmp = path.join(TMP_DIR, `resized-${crypto.randomUUID()}.jpg`);
      execFileSync('sips', ['-s', 'format', 'jpeg', '-Z', String(maxDim), imgPath, '--out', tmp], { stdio: 'ignore' });
      if (fs.existsSync(tmp)) {
        srcPath = tmp;
        mime = 'image/jpeg';
      }
    }
  } catch {
    // fall back to reading the original file below
  }
  try {
    const buf = fs.readFileSync(srcPath);
    if (buf.length > 6 * 1024 * 1024) return null; // guard against runaway HTML payloads
    return `data:${mime};base64,${buf.toString('base64')}`;
  } catch {
    return null;
  }
}

function readSvgInline(svgPath: string): string | null {
  try {
    let text = fs.readFileSync(svgPath, 'utf8');
    if (text.length > 200 * 1024) return null;
    text = text.replace(/<\?xml[^>]*\?>/, '').trim();
    if (!/^<svg/i.test(text)) return null;
    return text;
  } catch {
    return null;
  }
}

const HTML_ESCAPES: Record<string, string> = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

function escapeHtml(str: unknown): string {
  return String(str).replace(/[&<>"']/g, (c) => HTML_ESCAPES[c] ?? c);
}

